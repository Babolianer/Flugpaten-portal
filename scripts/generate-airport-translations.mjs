async function main() {
  const airportsPath = join(__dirname, '../data/airports.json')
  const airports = JSON.parse(readFileSync(airportsPath, 'utf-8'))

  const output = {
    countries: COUNTRY_TRANSLATIONS,
    cities: CITY_TRANSLATIONS,
    airports: {},
  }

  // Für jeden Flughafen: übersetzte Varianten für Such-Aliases erstellen
  for (const a of airports) {
    const cityKey = (a.city || '').toLowerCase().trim()
    const countryKey = (a.country || '').trim()
    const cityTr = CITY_TRANSLATIONS[cityKey] || { de: a.city, en: a.city, es: a.city, fr: a.city }
    const countryTr = COUNTRY_TRANSLATIONS[countryKey] || { de: a.country, en: a.country, es: a.country, fr: a.country }

    output.airports[a.iata] = {
      city: cityTr,
      country: countryTr,
      // Such-Aliases: alle Sprachen für Fuse.js
      searchAliases: [
        cityTr.de,
        cityTr.en,
        cityTr.es,
        cityTr.fr,
        a.iata,
        a.name,
      ].filter(Boolean),
    }
  }

  const outPath = join(__dirname, '../data/airport-translations.json')
  writeFileSync(outPath, JSON.stringify(output, null, 0), 'utf-8')
  console.log(`Written airport-translations.json with ${Object.keys(output.airports).length} airports`)
}

main().catch(console.error)
